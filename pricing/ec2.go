// EC2Pricing holds hourly On-Demand rates (Linux, shared tenancy) for a subset
// of EC2 instance types, by region. Rates fetched from the AWS Price List API;
// see PricesAsOf for when.
//
// This table is the FALLBACK truffle uses when the Price List API is
// unavailable — no credentials, no network, or the API throttling under a
// concurrent fan-out. truffle looks up an exact (region, instanceType) pair and
// errors when the table has no entry, because a fabricated price is worse than
// no price: nothing downstream can tell the difference (truffle#114).
//
// IT NOW COVERS GRAVITON, which is the point. Until truffle#175 the table had no
// Graviton compute, general-purpose or memory family in ANY region — no c6g-c9g,
// no m6g-m8g, no r6g-r9g — so a throttled Price List call plus --cost-limit
// REFUSED any Graviton launch outright. The failure was reported from a real
// eight-way fan-out across four Graviton generations.
//
// The previous version of this comment said the table "must not be grown into"
// a pricing database, on the grounds that hand-maintained prices go stale
// invisibly. That argument lost, and it is worth recording why: truffle IS the
// suite's pricing authority, so a fallback that cannot price the architecture
// most of its users run is a defect in truffle rather than a line to document
// around. Checked against the live API before writing these, four of the
// pre-existing 2026-01 entries were still exact nine months later, so On-Demand
// rates move far less than the staleness worry assumed.
//
// HOW TO REFRESH, since "it will go stale" is still true, just slower:
//
//	scripts/refresh-prices.sh          # re-fetch every entry from the Price List API
//	go test ./pricing/ -run Consistency # catch a typo before it reaches a spend cap
//
// The consistency test is the real guard. EC2 On-Demand scales linearly with
// size inside a family, so a mistyped digit breaks linearity and fails — which
// catches the error class that actually matters here, a price that is wrong
// rather than merely old.
//
// Coverage is still deliberately partial for GPU and accelerator families: there
// is no GPU family newer than p4d, so g6, g6e, g7e, p5, p5e, p6-*, trn* and inf*
// are absent and will not resolve here.
// PricesAsOf is when the rates in EC2Pricing were fetched from the Price List
// API. A value rather than a comment so a caller — or a test — can reason about
// the table's age instead of a reader having to notice a sentence.
